-- Step 2: create the raw tables and load the Synthea files.
-- Run AFTER 01_setup.sql and AFTER uploading the 8 .csv.gz files to @RAW.SYNTHEA.SYNTHEA_STAGE.
-- Every column lands as VARCHAR on purpose: casting to dates and numbers happens in your dbt staging models.

USE ROLE TRANSFORMER;
USE WAREHOUSE TRANSFORM_WH;
USE SCHEMA RAW.SYNTHEA;

LIST @SYNTHEA_STAGE;  -- you should see 8 files

-- patients
CREATE OR REPLACE TABLE PATIENTS (
    ID VARCHAR,
    BIRTHDATE VARCHAR,
    DEATHDATE VARCHAR,
    SSN VARCHAR,
    DRIVERS VARCHAR,
    PASSPORT VARCHAR,
    PREFIX VARCHAR,
    FIRST VARCHAR,
    MIDDLE VARCHAR,
    LAST VARCHAR,
    SUFFIX VARCHAR,
    MAIDEN VARCHAR,
    MARITAL VARCHAR,
    RACE VARCHAR,
    ETHNICITY VARCHAR,
    GENDER VARCHAR,
    BIRTHPLACE VARCHAR,
    ADDRESS VARCHAR,
    CITY VARCHAR,
    STATE VARCHAR,
    COUNTY VARCHAR,
    FIPS VARCHAR,
    ZIP VARCHAR,
    LAT VARCHAR,
    LON VARCHAR,
    HEALTHCARE_EXPENSES VARCHAR,
    HEALTHCARE_COVERAGE VARCHAR,
    INCOME VARCHAR
);
COPY INTO PATIENTS FROM @SYNTHEA_STAGE/patients.csv.gz FILE_FORMAT = (FORMAT_NAME = 'CSV_SKIP_HEADER') ON_ERROR = 'ABORT_STATEMENT';

-- encounters
