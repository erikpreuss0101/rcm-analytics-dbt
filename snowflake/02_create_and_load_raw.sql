    REASONDESCRIPTION VARCHAR
);
COPY INTO ENCOUNTERS FROM @SYNTHEA_STAGE/encounters.csv.gz FILE_FORMAT = (FORMAT_NAME = 'CSV_SKIP_HEADER') ON_ERROR = 'ABORT_STATEMENT';

