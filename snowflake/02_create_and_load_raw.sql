-- Check the row counts
SELECT 'patients' AS table_name, COUNT(*) AS row_count FROM PATIENTS
UNION ALL
SELECT 'encounters' AS table_name, COUNT(*) AS row_count FROM ENCOUNTERS
UNION ALL
SELECT 'providers' AS table_name, COUNT(*) AS row_count FROM PROVIDERS
UNION ALL
SELECT 'organizations' AS table_name, COUNT(*) AS row_count FROM ORGANIZATIONS
UNION ALL
SELECT 'payers' AS table_name, COUNT(*) AS row_count FROM PAYERS
UNION ALL
SELECT 'payer_transitions' AS table_name, COUNT(*) AS row_count FROM PAYER_TRANSITIONS
UNION ALL
SELECT 'claims' AS table_name, COUNT(*) AS row_count FROM CLAIMS
UNION ALL
SELECT 'claims_transactions' AS table_name, COUNT(*) AS row_count FROM CLAIMS_TRANSACTIONS;
